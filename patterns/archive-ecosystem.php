<p>At troposfera.xyz, juggling is art. Expression and exploration become ways of sensing the world and understanding our place within it. Founded by artist and juggler Dídac Gilabert, troposfera.xyz is a space where juggling, sound, and movement converge in a living artistic ecosystem.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Seeing art as a web of interconnected experiences, we explore spaces where juggling merges with generative soundscapes, music, and ambient atmospheres. Our ecosystem, with roles like Substrate, Catalysts, Synthesizers, and Enzymes, brings art into a shared flow that moves through every interaction.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We invite you to be part of this. Follow our explorations, join a workshop, or simply connect with us.</p>
<!-- /wp:paragraph -->

